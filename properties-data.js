// Check catalogue consistency while testing.
(function validateCatalogue() {
  const properties = window.GRAND_PROPERTIES;
  const ids = properties.map(item => item.id);
  const images = properties.map(item => item.image);

  if (new Set(ids).size !== ids.length) {
    console.warn("GrandSignature: Duplicate property IDs found.");
  }

  if (new Set(images).size !== images.length) {
    console.warn("GrandSignature: Duplicate image URLs found.");
  }

  console.info(
    "GrandSignature catalogue:",
    properties.length,
    "properties;",
    new Set(images).size,
    "distinct image URLs."
  );
})();
